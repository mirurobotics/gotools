func TestIsExampleFunc(t *testing.T) {
	tests := []struct {
		name string
		file string
		src  string
		want bool
	}{
		{"bare Example", "foo_test.go", "func Example() {}", true},
		{"Example for a name", "foo_test.go", "func ExampleFoo() {}", true},
		{"Example with suffix", "foo_test.go", "func Example_suffix() {}", true},
		{"lowercase after prefix", "foo_test.go", "func Examplehelper() {}", false},
		{"method", "foo_test.go", "func (T) ExampleM() {}", false},
		{"other name", "foo_test.go", "func TestFoo() {}", false},
		{"not a test file", "foo.go", "func Example() {}", false},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			got := IsExampleFunc(tc.file, parseFunc(t, tc.src))
			if got != tc.want {
				t.Errorf("IsExampleFunc(%q, %q) = %v", tc.file, tc.src, got)
			}
		})
	}
}

func TestIsTestFunc(t *testing.T) {
	tests := []struct {
		name string
		src  string
		want bool
	}{
		{"Test", "func TestFoo() {}", true},
		{"Benchmark", "func BenchmarkFoo() {}", true},
		{"Fuzz", "func FuzzFoo() {}", true},
		{"Example", "func ExampleFoo() {}", true},
		{"bare prefix", "func Test() {}", true},
		{"underscore after prefix", "func Test_foo() {}", true},
		{"digit after prefix", "func Test2() {}", true},
		{"lowercase after Test", "func Testable() {}", false},
		{"lowercase after Example", "func Examples() {}", false},
		{"lowercase after Benchmark", "func Benchmarks() {}", false},
		{"lowercase after Fuzz", "func Fuzzy() {}", false},
		{"method", "func (T) TestFoo() {}", false},
		{"other name", "func helper() {}", false},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			if got := IsTestFunc(parseFunc(t, tc.src)); got != tc.want {
				t.Errorf("IsTestFunc(%q) = %v, want %v", tc.src, got, tc.want)
			}
		})
	}
}

func parseFunc(t *testing.T, src string) *ast.FuncDecl {
	t.Helper()
	file, err := parser.ParseFile(token.NewFileSet(), "x.go", "package x\n"+src, 0)
	if err != nil {
		t.Fatal(err)
	}
	decl, ok := file.Decls[0].(*ast.FuncDecl)
	if !ok {
		t.Fatalf("first decl is %T, want *ast.FuncDecl", file.Decls[0])
	}
	return decl
}
