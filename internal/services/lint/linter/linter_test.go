func TestDiagnostic_String(t *testing.T) {
	d := analysis.Diagnostic{File: "foo.go", Line: 42, Message: "bad imports"}
	want := "foo.go:42: bad imports"
	got := d.String()
	if got != want {
		t.Errorf("got %q, want %q", got, want)
	}
}

